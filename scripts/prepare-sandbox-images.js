const fs = require("fs");
const path = require("path");
const { spawnSync } = require("child_process");

const root = path.join(__dirname, "..");
const sandboxDir = path.join(root, "tools", "sandbox-images");
const lockPath = path.join(sandboxDir, "images.lock.json");

const definitions = [
  {
    key: "python",
    tag: process.env.VERA_SANDBOX_IMAGE_PYTHON || "vera-sandbox-python:stable",
    dockerfile: "python.Dockerfile",
  },
  {
    key: "javascript",
    tag: process.env.VERA_SANDBOX_IMAGE_JAVASCRIPT || "vera-sandbox-javascript:stable",
    dockerfile: "javascript.Dockerfile",
  },
  {
    key: "shell",
    tag: process.env.VERA_SANDBOX_IMAGE_SHELL || "vera-sandbox-shell:stable",
    dockerfile: "shell.Dockerfile",
  },
];

function runCommand(command, args) {
  const result = spawnSync(command, args, {
    cwd: root,
    encoding: "utf8",
    stdio: ["ignore", "pipe", "pipe"],
  });
  if (result.status !== 0) {
    throw new Error(`${command} ${args.join(" ")} failed: ${result.stderr || result.stdout}`);
  }
  return (result.stdout || "").trim();
}

function ensureDocker() {
  runCommand("docker", ["version", "--format", "{{.Server.Version}}"]);
}

function buildImage(def) {
  const dockerfilePath = path.join(sandboxDir, def.dockerfile);
  runCommand("docker", ["build", "-f", dockerfilePath, "-t", def.tag, sandboxDir]);
}

function inspectDigest(tag) {
  const digest = runCommand("docker", ["image", "inspect", "--format", "{{index .RepoDigests 0}}", tag]);
  if (digest && digest !== "<no value>") return digest;
  return null;
}

function writeLock(images) {
  const payload = {
    generatedAt: new Date().toISOString(),
    note: "Generated by scripts/prepare-sandbox-images.js",
    images,
  };
  fs.writeFileSync(lockPath, JSON.stringify(payload, null, 2), "utf8");
}

function main() {
  ensureDocker();
  const images = {};
  for (const def of definitions) {
    console.log(`Building ${def.key} sandbox image as ${def.tag}...`);
    buildImage(def);
    const digest = inspectDigest(def.tag);
    images[def.key] = {
      tag: def.tag,
      digest,
    };
  }
  writeLock(images);
  console.log(`Sandbox image lock written to ${lockPath}`);
}

try {
  main();
} catch (err) {
  console.error("Failed to prepare sandbox images:", err.message);
  process.exit(1);
}
